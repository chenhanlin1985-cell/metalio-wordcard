"""Compile the reviewed teaching analyses. No suffix matching is done on the device."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "resources/vocabulary"
INCLUDE = ROOT / "firmware/components/native_learning/include/word_formation_data.inc"


def read_table(path):
    rows = {}
    for line_no, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not raw or raw.startswith("#"):
            continue
        fields = raw.split("\t")
        if len(fields) != 2 or not all(fields) or fields[0] in rows:
            raise ValueError(f"{path.name}:{line_no}: incomplete or duplicate row")
        rows[fields[0]] = fields[1]
    return rows


def component(key):
    """Keep the lexical role distinct from the sense of a particular affix."""
    form = key.split("@", 1)[0]
    if form.startswith("~"):
        return form[1:], "Root"
    if form.startswith("-"):
        return form, "Suffix"
    if form.endswith("-"):
        return form, "Prefix"
    return form, "Base"


def teaching_head(word, choices):
    choice = choices[word]
    if choice.startswith(">"):
        target = choice[1:]
        if target not in choices or choices[target] == "=" or choices[target].startswith(">"):
            raise ValueError(f"Unknown or unanalyzed teaching form for {word}: {target}")
        return target
    return word


def build(choices, meanings):
    indexes = {}
    parts = []
    for key, gloss in sorted(meanings.items()):
        if not re.fullmatch(r"(?:~?[a-z]+(?: [a-z]+)*|[a-z]+-|\-(?:[a-z]+|'s))(?:@[a-z]+)?", key):
            raise ValueError(f"Invalid part key {key!r}")
        if not re.search(r"[\u3400-\u9fff]", gloss):
            raise ValueError(f"Missing Chinese meaning for {key}")
        form, role = component(key)
        indexes[key] = len(parts)
        parts.append(f"    {{{quote(form)}, {quote(gloss)}, PartRole::{role}}},")
    refs, entries, aliases, used = [], [], [], set()
    for word, choice in sorted(choices.items()):
        if word != word.strip().lower():
            raise ValueError(f"Not a canonical headword: {word}")
        if choice == "=":
            continue
        target = teaching_head(word, choices)
        if target != word:
            aliases.append(f"    {{{quote(word)}, {quote(target)}}},")
            continue
        keys = choice.split("|")
        if not 2 <= len(keys) <= 8 or not re.fullmatch(r"[a-z]+(?:[ '-][a-z]+)*", word):
            raise ValueError(f"Invalid analysis for {word}: {choice}")
        if not any(component(k)[1] in ("Base", "Root") for k in keys):
            raise ValueError(f"No lexical component in {word}")
        if unknown := set(keys) - meanings.keys():
            raise ValueError(f"Undefined components in {word}: {unknown}")
        entries.append(f"    {{{quote(word)}, {len(refs)}, {len(keys)}}},")
        refs.extend(indexes[k] for k in keys)
        used.update(keys)
    if len(refs) >= 65536 or len(parts) >= 65536:
        raise ValueError("Formation index exceeds its uint16_t storage")
    if unused := meanings.keys() - used:
        raise ValueError(f"Unused component meanings: {sorted(unused)}")
    reference_lines = [
        "    " + ", ".join(str(n) for n in refs[start:start + 20]) + ","
        for start in range(0, len(refs), 20)
    ]
    return "\n".join([
        "// Generated by tools/build_word_formation.py. See resources/vocabulary/word-formation-license.md.",
        "inline constexpr PartData part_data[] = {", *parts, "};",
        "inline constexpr std::uint16_t part_refs[] = {", *reference_lines, "};",
        "inline constexpr Entry entries[] = {", *entries, "};",
        "inline constexpr Alias aliases[] = {", *aliases, "};", "",
    ])


def quote(text):
    return json.dumps(text, ensure_ascii=False)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare the committed index with both source tables")
    args = parser.parse_args()
    choices = read_table(DATA / "word-formation.tsv")
    meanings = read_table(DATA / "word-parts.tsv")
    generated = build(choices, meanings)
    if args.check:
        if INCLUDE.read_text(encoding="utf-8") != generated:
            raise SystemExit("The compiled index differs from its reviewed source")
    else:
        INCLUDE.write_bytes(generated.encode("utf-8"))
    print(f"{len(choices)} decisions, {sum(x != '=' for x in choices.values())} analyses, {len(meanings)} part meanings")


if __name__ == "__main__":
    main()
